"""Profile helpers behind the `profile` commands (no I/O here)."""

import datetime as dt
from typing import Any

import yaml

from endurance_planner.models.profile import Profile
from endurance_planner.schemas import schema_header
from endurance_planner.thresholds import resolve_thresholds
from endurance_planner.zones import zone_set, zone_tables

# Order in which training days are picked by the init wizard, and their default minutes.
STARTER_DAY_ORDER = ["sat", "tue", "thu", "sun", "wed", "fri", "mon"]
STARTER_MINUTES = {"sat": (180, 90), "sun": (120, 75)}
STARTER_WEEKDAY_MINUTES = (60, 60)


def zone_report(profile: Profile, today: dt.date) -> str:
    """Resolved thresholds warnings and zone tables, as plain text."""
    thresholds, issues = resolve_thresholds(profile, today)
    lines = [str(issue) for issue in issues]
    for title, rows in zone_tables(thresholds, zone_set(profile.thresholds.zone_models)).items():
        lines += ["", title]
        lines += [f"  {row.name:<22}{row.label}" for row in rows]
    return "\n".join(lines).strip() + "\n"


def starter_profile(
    *,
    name: str,
    ftp_w: float | None,
    threshold_pace: str | None,
    bike_hours: float,
    run_hours: float,
    days_per_week: int,
    weekly_hours_budget: float,
    goal_name: str,
    goal_date: dt.date,
    goal_type: str,
) -> dict[str, Any]:
    """Minimal profile from the required answers; everything else keeps its default."""
    thresholds: dict[str, Any] = {}
    if ftp_w is not None:
        thresholds["bike"] = {"ftp_w": ftp_w}
    if threshold_pace is not None:
        thresholds["run"] = {"threshold_pace": threshold_pace}
    training_days = STARTER_DAY_ORDER[:days_per_week]
    weekdays: dict[str, Any] = {}
    for day in ["mon", "tue", "wed", "thu", "fri", "sat", "sun"]:
        if day not in training_days:
            weekdays[day] = "rest"
            continue
        bike, run = STARTER_MINUTES.get(day, STARTER_WEEKDAY_MINUTES)
        weekdays[day] = {
            "bike": bike if ftp_w is not None else 0,
            "run": run if threshold_pace else 0,
        }
    return {
        "athlete": {"name": name},
        "thresholds": thresholds,
        "current_fitness": {"weekly_hours": {"bike": bike_hours, "run": run_hours}},
        "availability": {
            "days_per_week": days_per_week,
            "weekly_hours_budget": weekly_hours_budget,
            "weekdays": weekdays,
            "long_session_day": training_days[0],
        },
        "goals": [{"name": goal_name, "date": goal_date, "type": goal_type, "priority": "A"}],
        "preferences": {"primary_sport": "bike" if ftp_w is not None else "run"},
    }


def dump_profile(data: dict[str, Any]) -> str:
    header = schema_header()
    header += "# Generated by `endurance-planner profile init`. See examples/profile.example.yaml\n"
    header += "# for every available field and its default.\n"
    return header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True)
